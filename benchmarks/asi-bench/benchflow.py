"""Convert Asi Bench instances into BenchFlow (Harbor-format) task dirs.

Scaffold generated by ``bench eval adopt asi-bench --scaffold-only``. Fill in the TODOs: read
the source benchmark, map each instance to a Harbor task tree, and write it
under ``--output-dir``. See the reference implementation
``benchmarks/programbench/benchflow.py`` for the full contract.
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

logger = logging.getLogger(__name__)


def convert(
    source_instance: object, output_dir: Path, *, overwrite: bool = False
) -> Path:
    """Convert a single source instance into one Harbor task directory.

    Documented entry point for the converter. Each generated task directory
    must contain ``task.toml``, ``instruction.md``, ``environment/Dockerfile``
    and ``tests/test.sh``. Returns the task dir path.
    """
    raise NotImplementedError(
        "Implement asi-bench conversion (source instance → task dir)"
    )


def convert_all(
    source_dir: Path,
    output_dir: Path,
    *,
    overwrite: bool = False,
    limit: int | None = None,
    task_ids: list[str] | None = None,
) -> list[Path]:
    """Convert every source instance under ``source_dir`` into a task dir."""
    raise NotImplementedError(
        "Implement asi-bench conversion (source instances → task dirs)"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description="Convert Asi Bench to BenchFlow.")
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--source-dir", type=Path, default=None)
    parser.add_argument("--limit", type=int, default=None)
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument("--task-ids", default=None, help="Comma-separated IDs")
    args = parser.parse_args()

    ids = args.task_ids.split(",") if args.task_ids else None
    generated = convert_all(
        args.source_dir,
        args.output_dir,
        overwrite=args.overwrite,
        limit=args.limit,
        task_ids=ids,
    )
    logger.info("Generated %d asi-bench tasks in %s", len(generated), args.output_dir)


if __name__ == "__main__":
    main()
